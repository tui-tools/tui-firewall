func TestParseSaveReadsTheCloudImage(t *testing.T) {
	dump, err := ParseSave(V4, fixture(t, "oci-iptables-save.txt"))
	if err != nil {
		t.Fatalf("ParseSave: %v", err)
	}
	if dump.Version != "1.8.10" || dump.Variant != "nf_tables" {
		t.Errorf("version/variant = %q/%q, want 1.8.10/nf_tables", dump.Version, dump.Variant)
	}
	var names []string
	for _, table := range dump.Tables {
		names = append(names, table.Name)
	}
	if !reflect.DeepEqual(names, []string{"mangle", "filter", "nat"}) {
		t.Errorf("tables = %v", names)
	}
	input, ok := dump.Chain(TableFilter, ChainInput)
	if !ok {
		t.Fatal("no INPUT chain")
	}
	if len(input.Rules) != 9 || input.Policy != TargetAccept {
		t.Fatalf("INPUT = %d rules, policy %q; want 9, ACCEPT", len(input.Rules), input.Policy)
	}
	at, rule := input.CatchAll()
	if at != 9 || rule.Match.Target != TargetReject {
		t.Errorf("catch-all = %d (%+v), want rule 9, a REJECT", at, rule.Match)
	}
	if got := rule.Match.TargetDetail(); got != "-j REJECT --reject-with icmp-host-prohibited" {
		t.Errorf("target detail = %q", got)
	}
	// The counter prefix is read, and not part of the rule's identity.
	if input.Rules[0].Counter == nil || strings.HasPrefix(input.Rules[0].Spec, "[") {
		t.Errorf("first rule = %+v: counter not split from the spec", input.Rules[0])
	}
	// The jump into tailscale's chain is a jump, not a verdict.
	if input.Rules[0].Match.Target != "ts-input" || input.Rules[0].Match.Terminal() {
		t.Errorf("rule 1 = %+v, want a jump to ts-input", input.Rules[0].Match)
	}
}

func TestParseSaveKeepsAQuotedCommentAsOneWord(t *testing.T) {
	dump, err := ParseSave(V4, fixture(t, "oci-iptables-save.txt"))
	if err != nil {
		t.Fatalf("ParseSave: %v", err)
	}
	chain, _ := dump.Chain(TableFilter, "InstanceServices")
	if len(chain.Rules) == 0 {
		t.Fatal("InstanceServices is empty")
	}
	m := chain.Rules[0].Match
	if !strings.HasPrefix(m.Comment, "See the Oracle-Provided Images section") {
		t.Errorf("comment = %q", m.Comment)
	}
	if m.Dst != "169.254.0.2/32" || m.Proto != "tcp" || m.DPort != "3260" {
		t.Errorf("match = %+v", m)
	}
	// -m owner has no column: it is kept as text rather than dropped.
	if !reflect.DeepEqual(m.Unmodeled, []string{"-m owner", "--uid-owner 0"}) {
		t.Errorf("unmodeled = %q", m.Unmodeled)
	}
}

